#!/usr/bin/env python3
"""Generate latex/paired8_results.tex for the updated paper.

oGMemory numbers come from the new 8-video 4-way parallel run
(m3_parallel4_paper8_20261113); M3-Agent reference numbers are HELD from the
frozen m3_paper_paired8_20261103 comparison (unchanged). Adds the QA token-budget
Pareto section. Reads frozen artifacts only; no inference.
"""
import collections
import json
from pathlib import Path

ROOT = Path("/home/yuanjian/Development/memory-eval")
NAME = "m3_parallel4_paper8_20261113"
EXP = ROOT / "experiments" / NAME
OLD = json.loads((ROOT / "experiments/m3_paper_paired8_20261103/comparison.json").read_text())
OUT = ROOT / "latex" / "paired8_results.tex"

TEN_EXP = ROOT / "experiments/m3_ten_fullinterval_20261102"
TYPE_ORDER = [
    "Person Understanding",
    "Multi-Detail Reasoning",
    "Cross-Modal Reasoning",
    "General Knowledge Extraction",
    "Multi-Hop Reasoning",
]
TYPE_CN = {
    "Person Understanding": "人物理解",
    "Multi-Detail Reasoning": "多细节推理",
    "Cross-Modal Reasoning": "跨模态推理",
    "General Knowledge Extraction": "通用知识抽取",
    "Multi-Hop Reasoning": "多跳推理",
}


def compute_bytype(vids):
    """Per-question-type accuracy for the 8-video cohort (multi-label)."""
    qtype = {}
    for v in vids:
        for r in load_jsonl(ROOT / "runs/m3_ten_fullinterval_20261102/m3_qa" / v / "m3_qa_results.jsonl"):
            qtype[r["question_id"]] = r["type"]
    og = {r["question_id"]: r.get("score", 0.0) for r in load_jsonl(EXP / "judgments.jsonl")}
    m3 = {}
    for r in load_jsonl(TEN_EXP / "joint_questions.jsonl"):
        if r["method"] == "m3_reference_text" and r["video_id"] in vids:
            m3[r["question_id"]] = r.get("judge_score") or 0.0
    assert set(og) == set(m3), "qid mismatch between oGMemory and M3"
    qids = list(og)
    rows = []
    for t in TYPE_ORDER:
        ids = [q for q in qids if t in qtype.get(q, [])]
        n = len(ids)
        ogs = sum(og[q] for q in ids) / n
        m3s = sum(m3[q] for q in ids) / n
        ogfull = sum(1 for q in ids if og[q] == 1.0) / n
        m3full = sum(1 for q in ids if m3[q] == 1.0) / n
        rows.append(dict(type=t, n=n, og=ogs, m3=m3s, delta=ogs - m3s, ogfull=ogfull, m3full=m3full))
    og_all = sum(og.values()) / len(qids)
    m3_all = sum(m3.values()) / len(qids)
    overall = dict(type="ALL", n=len(qids), og=og_all, m3=m3_all, delta=og_all - m3_all,
                   ogfull=sum(1 for q in qids if og[q] == 1.0) / len(qids),
                   m3full=sum(1 for q in qids if m3[q] == 1.0) / len(qids))
    return rows, overall


def load_jsonl(p):
    return [json.loads(s) for s in Path(p).read_text().splitlines() if s.strip()]


def main():
    m3 = OLD["methods"]["m3_agent"]
    vids = OLD["cohort"]

    js = load_jsonl(EXP / "judgments.jsonl")
    by = collections.defaultdict(lambda: [0, 0.0])
    for r in js:
        by[r["video_id"]][0] += 1
        by[r["video_id"]][1] += r.get("score", 0)
    og_mean = sum(r["score"] for r in js) / len(js)
    og_valid = sum((not r.get("error")) and bool(r.get("predicted_answer")) for r in js)
    og_full = sum(r["score"] == 1 for r in js) / len(js)

    split = json.loads((EXP / "og_stage_split.json").read_text())["totals"]
    vids_qa = json.loads((EXP / "qa_budget_per_video.json").read_text())["videos"]
    pin = pout = pcache = 0
    for v in vids_qa:
        for r in load_jsonl(EXP / f"usage-qa-{v}.jsonl"):
            u = r.get("usage") or {}
            pin += u.get("prompt_tokens", 0) or 0
            pout += u.get("completion_tokens", 0) or 0
            pcache += (u.get("prompt_tokens_details") or {}).get("cached_tokens", 0) or 0
    og_mem_tok = 2510031 + 785051
    og_qa_tok = pin + pout
    og_total_tok = og_mem_tok + og_qa_tok
    og_time = {
        "shared_perception": split["shared"],
        "memory_and_index": split["mem"],
        "qa": split["qa"],
    }
    og_time["allocated_total"] = sum(og_time.values())

    sweep = json.loads((EXP / "qa_budget_sweep_results.json").read_text())["points"]
    pareto = json.loads((EXP / "qa_budget_pareto_results.json").read_text())["pareto_front"]
    pareto_budgets = {p["budget"] for p in pareto}
    ms = json.loads((EXP / "qa_budget_multiseed_results.json").read_text())
    ms_agg = {int(k): v for k, v in ms["aggregate"].items()}

    L = []
    a = L.append
    a("% Generated by scripts/gen_paper_results_20261116.py; oGMemory = 4-way parallel run, M3-Agent held.")
    # ---- Table: per-video scores ----
    a(r"\begin{table}[htbp]\centering\small")
    a(r"\caption{逐视频自动评分（百分数）；oGMemory为本次四路并行复跑，M3-Agent沿用冻结参考结果；"
      r"分差按未舍入值计算，保留全部97题，失败计零。}")
    a(r"\label{tab:videos}\begin{tabular}{lrrrr}\toprule")
    a(r"视频 & 题数 & oGMemory & M3-Agent & 分差（百分点）\\\midrule")
    for v in vids:
        n, s = by[v]
        og = s / n
        mm = m3["by_video"][v]["mean_score"]
        a(r"\code{" + v + f"}} & {n} & {100*og:.1f}\\% & {100*mm:.1f}\\% & {100*(og-mm):+.1f}\\\\")
    a(r"\midrule")
    a(f"题目加权合计 & 97 & {100*og_mean:.1f}\\% & {100*m3['mean_score']:.1f}\\% & "
      f"{100*(og_mean-m3['mean_score']):+.1f}\\\\")
    a(r"\bottomrule\end{tabular}\end{table}")
    # ---- Figure: scores ----
    a(r"\begin{figure}[htbp]\centering")
    a(r"\includegraphics[width=\linewidth]{figures/paired8_final_scores.pdf}")
    a(r"\caption{两方法逐视频表现及题目加权均值。oGMemory为四路并行复跑；纵轴为自动评分而非人工准确率；"
      r"M3-Agent为同模型参考适配的冻结结果，未随本次复跑改动。}\label{fig:scores}\end{figure}")
    # ---- Table + Figure: by question type ----
    bt_rows, bt_all = compute_bytype(vids)
    a(r"\begin{table}[htbp]\centering\small")
    a(r"\caption{按题型自动评分（百分数，题目多标签）；同一8视频/97题子集，oGMemory为四路并行复跑、"
      r"M3-Agent为冻结参考。一题含某题型即计入该题型，故各行题数和（166）大于97题。}")
    a(r"\label{tab:bytype}\setlength{\tabcolsep}{4pt}\begin{tabular}{lrrrrr}\toprule")
    a(r"题型 & 题数 & oGMemory & M3-Agent & 分差（百分点） & oGMemory全分率\\\midrule")
    for r in bt_rows:
        a(r"\code{" + r["type"].replace(" ", "\ ") + r"} & %d & %.1f\%% & %.1f\%% & %+.1f & %.1f\%%\\" % (
            r["n"], 100*r["og"], 100*r["m3"], 100*r["delta"], 100*r["ogfull"]))
    a(r"\midrule")
    a(r"整体（97 题） & %d & %.1f\%% & %.1f\%% & %+.1f & %.1f\%%\\" % (
        bt_all["n"], 100*bt_all["og"], 100*bt_all["m3"], 100*bt_all["delta"], 100*bt_all["ogfull"]))
    a(r"\bottomrule\end{tabular}")
    a(r"\par\smallskip\footnotesize 多标签：一题按其标注的每个题型分别计入；Multi-Hop仅5题，样本小、波动大，需谨慎解读。")
    a(r"\end{table}")
    a(r"\begin{figure}[htbp]\centering")
    a(r"\includegraphics[width=\linewidth]{figures/paired8_final_bytype.pdf}")
    a(r"\caption{按题型的自动评分对比。oGMemory在五类题型上均高于M3-Agent，整体分差20.1个百分点，"
      r"多细节推理差距最大（+25.0）；通用知识抽取两者均最低，为共同短板。}\label{fig:bytype}\end{figure}")
    # ---- Table: resources ----
    a(r"\begin{table}[htbp]\centering\small")
    a(r"\caption{同一八视频子集的质量与资源开销。M为百万token，时间单位为分钟。oGMemory为本分支四路并行复跑、M3-Agent为冻结参考，二者为独立运行，共享感知分别测得。}")
    a(r"\label{tab:resources}\begin{tabular}{lrr}\toprule")
    a(r"指标 & oGMemory & M3-Agent\\\midrule")
    pairs = [
        ("有效回答", f"{og_valid}/97", f"{m3['valid_answers']}/97"),
        (r"全分题比例（\%）", f"{100*og_full:.2f}", f"{100*m3['full_credit_fraction']:.2f}"),
        (r"QA输入（M）", f"{pin/1e6:.3f}", f"{m3['usage']['qa']['prompt_tokens']/1e6:.3f}"),
        (r"其中未缓存输入（M）", f"{(pin-pcache)/1e6:.3f}", f"{m3['usage']['qa']['uncached_prompt_tokens']/1e6:.3f}"),
        (r"QA输出，含推理（M）", f"{pout/1e6:.3f}", f"{m3['usage']['qa']['completion_tokens']/1e6:.3f}"),
        (r"已记录建忆+QA总token（M）", f"{og_total_tok/1e6:.3f}",
         f"{m3['usage']['memory_plus_qa']['total_tokens']/1e6:.3f}" + r"$^{*}$"),
        (r"共享感知与启动", f"{og_time['shared_perception']/60:.2f}", f"{m3['time_seconds']['shared_perception']/60:.2f}"),
        (r"记忆、图谱及索引", f"{og_time['memory_and_index']/60:.2f}", f"{m3['time_seconds']['memory_and_index']/60:.2f}"),
        (r"QA耗时", f"{og_time['qa']/60:.2f}", f"{m3['time_seconds']['qa']/60:.2f}"),
        (r"各自计入感知后的总时间", f"{og_time['allocated_total']/60:.2f}", f"{m3['time_seconds']['allocated_total']/60:.2f}"),
    ]
    for label, x, y in pairs:
        a(f"{label} & {x} & {y}\\\\")
    a(r"\bottomrule\end{tabular}")
    a(r"\par\smallskip\footnotesize $^{*}$M3建忆有1次失败请求未返回usage，该总量仅表示已记录用量，"
      r"不把未知值当作零；两方法QA用量完整。")
    a(r"\end{table}")
    # ---- Figure: resources ----
    a(r"\begin{figure}[htbp]\centering")
    a(r"\includegraphics[width=\linewidth]{figures/paired8_final_resources.pdf}")
    a(r"\caption{资源开销及阶段分布。左图为建忆与QA已记录的输入、输出总token，不含embedding和评委；"
      r"星号表示M3有未知建忆用量。右图按各自运行实测的阶段墙钟展示；oGMemory为四路并行复跑、"
      r"M3为冻结参考，二者为独立运行，共享感知亦分别测得，不能将两方法总时间相加当作单次实验墙钟时间。}"
      r"\label{fig:resources}\end{figure}")
    # ---- Table: QA budget sweep (multi-seed mean +/- std) ----
    a(r"\begin{table}[htbp]\centering\small")
    a(r"\caption{QA阶段token预算扫描（固定记忆不变，仅改\code{m3.qa\_context.max\_input\_tokens}，"
      r"每档独立重跑并重判97题）。每档$n=2$次独立QA采样，准确率为跨重复的均值$\pm$标准差；"
      r"有效上限$=\min(\text{预算},\,32768-8192-2048=22528)$。}")
    a(r"\label{tab:pareto}\begin{tabular}{rrrrrr}\toprule")
    a(r"预算 & 有效上限 & QA输入（M） & QA输出（M） & 准确率（\%，mean$\pm$std） & QA耗时（s）\\\midrule")
    for b in sorted(ms_agg):
        v=ms_agg[b]
        acc=v["accuracy_mean"]*100; sd=(v["accuracy_std"] or 0.0)*100
        a(f"{b} & {min(b,22528)} & {v['qa_input_tokens_mean']/1e6:.3f} & "
          f"{v['qa_output_tokens_mean']/1e6:.3f} & ${acc:.2f}\\pm{sd:.2f}$ & {v['qa_seconds_mean']:.1f}\\\\")
    a(r"\bottomrule\end{tabular}")
    a(r"\par\smallskip\footnotesize 每档为独立QA采样重复$n=2$；3000/4000新档各两次，6000--16000沿用单次并各补一次，"
      r"22528由两次独立满上下文运行合成；标准差反映QA生成与判分噪声。"
      r"12000与22528两档QA墙钟（分别约6512与16387秒）含配额等待与重试，远高于纯计算耗时，不用于比较各档计算效率。")
    a(r"\end{table}")
    # ---- Figure: per-video sweep (single explanatory figure) ----
    a(r"\begin{figure}[htbp]\centering")
    a(r"\includegraphics[width=0.92\linewidth]{figures/qa_budget_pareto_per_video.pdf}")
    a(r"\caption{逐视频准确率随QA token预算设置的变化（多seed均值$\pm$标准差）：每个视频一条彩色曲线（共8条，"
      r"误差棒来自独立QA重复），黑色粗实线为97题整体加权平均（同样带误差棒）。"
      r"整体准确率随预算单调上升至接近上下文上限；各视频最优预算不同，单一全局预算难以对所有视频最优。}"
      r"\label{fig:pareto-pervideo}\end{figure}")

    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)
    # echo key numbers
    print("OG mean=%.4f  M3 mean=%.4f  delta_pp=%.3f" % (og_mean, m3["mean_score"], 100*(og_mean-m3["mean_score"])))
    print("OG valid=%d full=%.4f  qa_in=%d qa_out=%d mem=%d total=%d" % (og_valid, og_full, pin, pout, og_mem_tok, og_total_tok))


if __name__ == "__main__":
    main()
